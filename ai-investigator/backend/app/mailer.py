"""SMTP handoff email (BugZero).

Sends the developer the evidence pack that a Jira ticket alone would lose:
the verdict, the quoted log lines that prove each link, the suspected code
location, and the Jira key once one exists. The ticket is the system of record;
this mail is the "someone looked at this, here is why" notification.

Transport is stdlib smtplib + email.mime. STARTTLS is used automatically when
the server advertises it, and SMTP_SSL is used for port 465. Nothing raises:
a mail failure returns {ok: False, error} so the investigation stands even when
the inbox is unreachable.

Dry-run is the default safety net: with no SMTP host configured, send() renders
the full message and returns it instead of transmitting, so the console can show
an operator exactly what would go out.
"""

import os
import smtplib
from email.message import EmailMessage

DISCLAIMER = ("Generated by BugZero from live log and database evidence. "
              "Proposal only — a human reviews, implements and deploys.")

MAX_BODY_CHARS = 60000


def config() -> dict:
    """SMTP settings from the environment. Empty host => dry-run mode."""
    from . import llmreason
    llmreason._load_dotenv()
    raw_to = os.environ.get("BUGZERO_MAIL_TO", "").strip()
    return {
        "host": os.environ.get("SMTP_HOST", "").strip(),
        "port": int(os.environ.get("SMTP_PORT", "587")),
        "user": os.environ.get("SMTP_USER", "").strip(),
        "password": os.environ.get("SMTP_PASSWORD", "").strip(),
        "from_addr": os.environ.get("BUGZERO_MAIL_FROM",
                                    "bugzero@localhost").strip(),
        "to_addrs": [a.strip() for a in raw_to.split(",") if a.strip()],
        "use_ssl": os.environ.get("SMTP_USE_SSL", "").strip().lower() in ("1", "true", "yes"),
        "timeout": int(os.environ.get("SMTP_TIMEOUT_SECONDS", "20")),
    }


def is_configured() -> bool:
    """True only when a host AND at least one recipient exist."""
    cfg = config()
    return bool(cfg["host"] and cfg["to_addrs"])


def build_message(subject: str, body: str, cfg: dict, to_addrs=None) -> EmailMessage:
    msg = EmailMessage()
    msg["From"] = cfg["from_addr"]
    msg["To"] = ", ".join(to_addrs or cfg["to_addrs"])
    msg["Subject"] = (subject or "BugZero incident")[:250]
    msg.set_content((body or "")[:MAX_BODY_CHARS])
    return msg


def send(subject: str, body: str, to_addrs=None) -> dict:
    """Transmit, or render without sending when SMTP is unconfigured.

    Returns {ok, mode: sent|dry-run, ...}. In dry-run the rendered message is
    returned so the console and the tests can both inspect exactly what a real
    send would have produced.
    """
    cfg = config()
    recipients = [a.strip() for a in (to_addrs or cfg["to_addrs"]) if a and a.strip()]
    if not recipients:
        return {"ok": False, "mode": "dry-run", "sent": False,
                "error": "No recipients — set BUGZERO_MAIL_TO (comma-separated)."}
    msg = build_message(subject, body, cfg, recipients)

    if not cfg["host"]:
        return {
            "ok": True, "mode": "dry-run", "sent": False,
            "detail": ("SMTP_HOST not set — message rendered, not transmitted. "
                       "Set SMTP_HOST / SMTP_PORT / SMTP_USER / SMTP_PASSWORD / "
                       "BUGZERO_MAIL_TO to send for real."),
            "to": recipients,
            "subject": msg["Subject"],
            "body_preview": (body or "")[:1500],
        }

    try:
        if cfg["use_ssl"] or cfg["port"] == 465:
            with smtplib.SMTP_SSL(cfg["host"], cfg["port"], timeout=cfg["timeout"]) as s:
                if cfg["user"]:
                    s.login(cfg["user"], cfg["password"])
                s.send_message(msg)
        else:
            with smtplib.SMTP(cfg["host"], cfg["port"], timeout=cfg["timeout"]) as s:
                s.ehlo()
                # Opportunistic STARTTLS: required in practice by every modern
                # relay, and silently unavailable only on local test servers.
                if s.has_extn("starttls"):
                    s.starttls()
                    s.ehlo()
                if cfg["user"]:
                    s.login(cfg["user"], cfg["password"])
                s.send_message(msg)
    except Exception as e:
        return {"ok": False, "mode": "smtp", "sent": False,
                "to": recipients, "subject": msg["Subject"],
                "error": f"{type(e).__name__}: {e}"}
    return {"ok": True, "mode": "smtp", "sent": True, "to": recipients,
            "subject": msg["Subject"]}


def health() -> dict:
    """Status row for the console: configured? do we have recipients?"""
    cfg = config()
    if not is_configured():
        missing = []
        if not cfg["host"]:
            missing.append("SMTP_HOST")
        if not cfg["to_addrs"]:
            missing.append("BUGZERO_MAIL_TO")
        return {"configured": False, "reachable": False,
                "detail": f"Email not configured ({', '.join(missing)}). Handoff runs in dry-run."}
    return {"configured": True, "reachable": True,
            "host": cfg["host"], "port": cfg["port"],
            "from": cfg["from_addr"], "to": cfg["to_addrs"],
            "detail": "ready"}